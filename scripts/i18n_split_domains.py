"""One-shot migration: split the 2-domain i18n tree into the 4 v0.11.0 domains.

Domain routing follows docs/I18N.md §2 — the criterion is WHO REPAINTS the
string, not which process reads it:

  overlay.json  ui.* overlay panel chrome (painted every frame)
  console.json  console.* console chrome (replayed by retranslateUi)
  reader.json   ui.reader.* (snapshot status, per-poll refresh)
  data.json     mantle.* / abnormality.* / ui.demo.* (pure data ids)

*** KEY NAMES ARE PRESERVED VERBATIM *** — including the `ui.` prefix on
reader and demo keys. That is deliberate. The audit (i18n-audit.md §5.3) and
PLAN.md (B8) both schedule the three-layer rename (`ui.reader.*` ->
`reader.*`, `ui.demo.*` -> `demo.*`, `ui.*` -> `overlay.panel.*`) as a
SEPARATE later batch, because that batch must change ~150 call sites in
src/**/*.cpp — files this task is not allowed to touch (see TASK_SPEC below).
Moving a key without moving its caller turns a live key into a missing key:
StringTable::tr() would silently return the dot-path and the overlay would
paint "ui.reader.waiting_exe" instead of a sentence. So this script does the
half that is safe alone — the file split — and leaves the call sites for T2.

Dead keys are DROPPED, never moved. The list is DEAD_KEYS below: every entry
was verified dead by scripts/i18n_unused_keys.py --tests and cross-checked by
hand against the four reference channels the regex gate scripts cannot see:

  * `kKeys[]` / `kNameKeys[]` / `kCorners[]` static arrays in code
    (panel_sections.h, hud_canvas.cpp) — plain literals, so the literal scan
    covers them; verified none of the dropped keys appear there.
  * `const char *stateKey = "...": "..."` ternary chains (control_panel.cpp
    :2188, :2300) — also plain literals, same coverage.
  * `QStringLiteral("mantle.%1").arg(id)` composed keys (string_table.h) —
    matched by the prefix rule in i18n_unused_keys.py, so all 21 mantle ids
    are correctly considered reachable and NONE of them is in DEAD_KEYS.
  * the tests/ tree (locale_sync_tests.cpp, snap_player_offline.cpp, ...),
    which keeps ui.app_title and ui.context_hunting alive.

Usage (from the repo root):
    python3 scripts/i18n_split_domains.py [--dry-run]
"""
