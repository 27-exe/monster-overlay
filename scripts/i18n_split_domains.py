def flatten(obj: dict, prefix: str = "") -> dict:
    """Nested object -> dot-path leaves, identical to StringTable::load()."""
    out = {}
    for key, value in obj.items():
        if key in SKIP_KEYS:
            continue
        path = f"{prefix}.{key}" if prefix else key
        if isinstance(value, dict):
            out.update(flatten(value, path))
        else:
            out[path] = value
    return out


def nest(flat: dict) -> dict:
    """dot-path flat map -> nested dict so the JSON stays readable."""
    root: dict = {}
    for key, value in flat.items():
        parts = key.split(".")
        node = root
        for part in parts[:-1]:
            node = node.setdefault(part, {})
        node[parts[-1]] = value
    return root


def route(key: str, value, dead: set):
    """Return (domain, new_key) or None when the key must be dropped.

    The key is NOT renamed — see the module docstring. Only the file changes.
    """
    if key in dead:
        return None
    if key.startswith("ui.reader."):
        return ("reader", key)
    if key.startswith("ui.demo."):
        return ("data", key)
    if key.startswith("mantle.") or key.startswith("abnormality."):
        return ("data", key)
    if key.startswith("console."):
        return ("console", key)
    # Everything else under ui.* is overlay panel chrome.
    return ("overlay", key)


def split_locale(locale: str, dead: set) -> dict:
    src = I18N / locale
    overlay = json.loads((src / "overlay.json").read_text(encoding="utf-8"))
    console = json.loads((src / "console.json").read_text(encoding="utf-8"))
    parts = {d: {} for d in DOMAINS}
    for key, value in {**flatten(overlay), **flatten(console)}.items():
        routed = route(key, value, dead)
        if routed is None:
            continue
        domain, new_key = routed
        parts[domain][new_key] = value
    return parts


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--dry-run", action="store_true",
                    help="print the routing table; write nothing")
    args = ap.parse_args(argv)

    dead = set(DEAD_KEYS)
    print(f"dropping {len(dead)} dead key(s)")

    for locale in LOCALES:
        parts = split_locale(locale, dead)
        print(f"\n{locale}:")
        for domain in DOMAINS:
            flat = parts[domain]
            print(f"  {domain}.json: {len(flat)} keys")
            # Invariant on every run: a dead key must never be carried over.
            bad = sorted(k for k in flat if k in dead)
            if bad:
                print(f"  !! LEAKED DEAD KEYS: {bad}", file=sys.stderr)
                return 1
            if args.dry_run:
                continue
            doc = {}
            note = META_NOTES[locale][domain]
            if note:
                doc["_meta"] = note
            doc.update(nest(flat))
            (I18N / locale / f"{domain}.json").write_text(
                json.dumps(doc, ensure_ascii=False, indent=2) + "\n",
                encoding="utf-8")

    if args.dry_run:
        return 0

    # The 2→4 split needs 8 files listed; rebuild the i18n block of the qrc.
    qrc = QRC.read_text(encoding="utf-8", errors="strict") if QRC.exists() else ""
    if not qrc:
        print(f"FAIL: unreadable {QRC}", file=sys.stderr)
        return 1
    kept = [ln for ln in qrc.splitlines(keepends=True)
            if not re.match(r"\s*<file>i18n/.*\.json</file>", ln)]
    entries = "".join(f"        <file>i18n/{loc}/{dom}.json</file>\n"
                      for loc in LOCALES for dom in DOMAINS)
    # NOTE (v0.11.0): this script already ran and its job is done. The
    # anchor below was the qrc layout of that time — monsters/parts.json has
    # since been deleted, so a fresh run now fails at the anchor check below.
    # That is expected: do NOT re-run this against the current tree. The
    # four-domain i18n layout it produced is the shipped state.
    anchor = "        <file>monsters/parts.json</file>\n"
    text2 = "".join(kept)
    if anchor not in text2:
        print(f"FAIL: qrc anchor not found: {anchor!r}", file=sys.stderr)
        return 1
    QRC.write_text(text2.replace(anchor, entries + anchor, 1), encoding="utf-8")

    # NOTE: there is nothing to delete. The 2→4 split keeps the SAME file
    # names for overlay/console (they are the domain names, not the old
    # process-oriented names), so the four files written above ARE the final
    # state. The pre-split content lived in exactly these paths and has been
    # overwritten — the old `unlink()` of the same paths here used to delete
    # the freshly-written files and leave only reader/data on disk.
    print("\nsplit complete: 4 domains x 2 locales")
    return 0


if __name__ == "__main__":
    sys.exit(main())
